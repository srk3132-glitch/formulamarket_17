import { ALL_CROPS, type CropCategory, type CropItem } from "./crops-data";
export { ALL_CROPS, type CropCategory, type CropItem };
export const CROPS = ALL_CROPS;
export type CropId = string;

export function cropName(id: string, lang: Lang): string {
  const crop = CROPS.find((c) => c.id === id);
  if (!crop) return id;
  const val = (crop as Record<string, unknown>)[lang];
  if (typeof val === "string" && val.trim()) return val;
  if (typeof (crop as Record<string, unknown>)["hi"] === "string" && lang !== "en") {
    return (crop as Record<string, unknown>)["hi"] as string;
  }
  return crop.en;
}

type LangContextValue = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: keyof typeof en | string) => string;
};

const LangContext = createContext<LangContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem("kb-lang") as Lang | null;
    if (stored && stored in DICTS) setLangState(stored);
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem("kb-lang", l);
  }, []);

  const value = useMemo<LangContextValue>(
    () => ({
      lang,
      setLang,
      t: (key: string) => DICTS[lang][key] ?? DICTS.en[key] ?? key,
    }),
    [lang, setLang],
  );

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useI18n must be used inside LanguageProvider");
  return ctx;
}
